@pytest.mark.django_db
class TestSiteSettings:
    def test_singleton_save(self):
        """Вторая запись перезаписывает первую (pk=1)."""
        SiteSettings.objects.create(name="A")
        SiteSettings.objects.create(name="B")
        assert SiteSettings.objects.count() == 1
        assert SiteSettings.load().name == "B"

    def test_load_creates_default(self):
        """load() создаёт дефолтную запись, если её нет."""
        assert not SiteSettings.objects.exists()
        obj = SiteSettings.load()
        assert obj.pk == 1
        assert obj.name == "Портфолио"


@pytest.mark.django_db
class TestContactRequest:
    def test_default_status(self):
        req = ContactRequest.objects.create(
            name="Иван",
            email="i@example.com",
            message="Текст сообщения",
        )
        assert req.status == ContactRequest.Status.NEW

    def test_str(self):
        req = ContactRequest.objects.create(
            name="Иван",
            email="i@example.com",
            message="Текст",
        )
        assert "Иван" in str(req)
        assert "i@example.com" in str(req)


@pytest.mark.django_db
class TestProject:
    def test_slug_autogenerated(self):
        p = Project.objects.create(
            name="Мой кейс",
            category=Project.Category.OTHER,
            short_description="x",
            task="x",
            solution="x",
            result="x",
            date="2026-01-01",
        )
        assert p.slug == "мой-кейс"  # было: "moy-keys"

    def test_unique_slug(self):
        for _ in range(3):
            Project.objects.create(
                name="Одинаковый",
                category=Project.Category.OTHER,
                short_description="x",
                task="x",
                solution="x",
                result="x",
                date="2026-01-01",
            )
        slugs = list(Project.objects.values_list("slug", flat=True))
        assert len(slugs) == len(set(slugs)), "slug должны быть уникальны"

    def test_get_absolute_url(self):
        p = Project.objects.create(
            name="Кейс",
            category=Project.Category.OTHER,
            short_description="x",
            task="x",
            solution="x",
            result="x",
            date="2026-01-01",
        )
        # Django 6.x кодирует кириллицу в URL — сравниваем декодированные версии
        assert unquote(p.get_absolute_url()) == f"/portfolio/{p.slug}/"


